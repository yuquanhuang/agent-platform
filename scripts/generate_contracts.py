def render_supporting_models() -> tuple[str, str]:
    resource = load_json(CONTRACT_ROOT / "schemas" / "resource-content-v1.schema.json")
    skill = load_json(CONTRACT_ROOT / "schemas" / "skill-manifest-v1.schema.json")
    sandbox = load_json(CONTRACT_ROOT / "schemas" / "sandbox-policy-v1.schema.json")
    resource_names, skill_names, sandbox_names, _ = schema_name_maps()

    combined: dict[str, Any] = {"$defs": {}}
    local_names: dict[str, str] = {}
    for prefix, document, names in (
        ("resource", resource, resource_names),
        ("skill", skill, skill_names),
        ("sandbox", sandbox, sandbox_names),
    ):
        root_pointer = f"#/$defs/{prefix}_root"
        combined["$defs"][f"{prefix}_root"] = document
        local_names[root_pointer] = names["#"]
        for pointer, type_name in names.items():
            if pointer == "#":
                continue
            def_name = pointer.rsplit("/", maxsplit=1)[-1]
            combined_pointer = f"#/$defs/{prefix}_{def_name}"
            combined["$defs"][f"{prefix}_{def_name}"] = document["$defs"][def_name]
            local_names[combined_pointer] = type_name

    external_names: dict[str, str] = {
        "skill-manifest-v1.schema.json": "SkillManifest",
        "sandbox-policy-v1.schema.json": "SandboxPolicy",
        "https://json-schema.org/draft/2020-12/schema": "JsonValue",
    }
    for type_name in local_names.values():
        external_names[f"generated://{type_name}"] = type_name
    for pointer, type_name in resource_names.items():
        if pointer != "#":
            external_names[pointer] = type_name

    renderer = SchemaRenderer(
        SchemaSource(
            document=combined,
            local_names=local_names,
            external_names=external_names,
        )
    )
    ordered_supporting_types = sorted(
        local_names.items(), key=lambda item: item[1] == "ResourceContent"
    )
    for pointer, name in ordered_supporting_types:
        schema = resolve_pointer(combined, pointer)
        if not isinstance(schema, Mapping):
            raise GenerationError(f"invalid supporting schema: {pointer}")
        adjusted = replace_local_refs(
            schema, pointer.split("_")[0], resource_names, skill_names
        )
        renderer.register(name, adjusted)
    return (
        renderer.render_python_module("Generated resource content DTOs."),
        renderer.render_typescript_module("Generated resource content DTOs."),
    )


def replace_local_refs(
    value: Any,
    prefix_hint: str,
    resource_names: Mapping[str, str],
    skill_names: Mapping[str, str],
) -> Any:
    """Map local refs from combined supporting documents to generated names."""

    if isinstance(value, list):
        return [
            replace_local_refs(item, prefix_hint, resource_names, skill_names)
            for item in value
        ]
    if not isinstance(value, Mapping):
        return value
    result: dict[str, Any] = {}
    for key, item in value.items():
        if key == "$ref" and isinstance(item, str) and item.startswith("#/$defs/"):
            names = skill_names if "skill" in prefix_hint else resource_names
            result[key] = f"generated://{names[item]}"
        else:
            result[key] = replace_local_refs(
                item, prefix_hint, resource_names, skill_names
            )
    return result


def render_run_event_models() -> tuple[str, str]:
    document = load_json(CONTRACT_ROOT / "schemas" / "run-event-v1.schema.json")
    _, _, _, run_event_names = schema_name_maps()
    external_names = {f"generated://{name}": name for name in run_event_names.values()}
    source = SchemaSource(
        document=document,
        local_names=run_event_names,
        external_names=external_names,
    )
    python_renderer = SchemaRenderer(source)
    typescript_renderer = SchemaRenderer(source)
    support_defs = [
        name
        for name in document.get("$defs", {})
        if name.endswith("_payload")
        or name in {"artifact_ref", "plan_step", "usage", "id"}
    ]
    for name in support_defs:
        schema = document["$defs"][name]
        type_name = run_event_names[f"#/$defs/{name}"]
        python_renderer.register(type_name, schema)
        typescript_renderer.register(type_name, schema)

    python_base = python_renderer.render_python_module(
        "Generated RunEvent payload DTOs."
    ).rstrip()
    python_base = python_base.replace(
        "from typing import Literal",
        "from typing import Annotated, Literal",
    )
    python_base = re.sub(
        r"from pydantic import ([^\n]+)",
        lambda match: f"from pydantic import {match.group(1)}, TypeAdapter",
        python_base,
        count=1,
    )
    typescript_base = typescript_renderer.render_typescript_module(
        "Generated RunEvent payload DTOs."
    ).rstrip()
    variants = run_event_variants(document)
    envelope = resolve_pointer(document, "#/$defs/envelope")
    runtime_candidate = resolve_pointer(document, "#/$defs/runtime_event_candidate")
    if not isinstance(envelope, Mapping) or not isinstance(runtime_candidate, Mapping):
        raise GenerationError("RunEvent envelope schemas are invalid")
    candidate_parts = runtime_candidate.get("allOf")
    if not isinstance(candidate_parts, list) or not candidate_parts:
        raise GenerationError("RuntimeEventCandidate must use allOf")
    candidate_envelope = candidate_parts[0]
    if not isinstance(candidate_envelope, Mapping):
        raise GenerationError("RuntimeEventCandidate envelope is invalid")

    python_extra = render_python_event_unions(
        python_renderer, envelope, candidate_envelope, variants
    )
    typescript_extra = render_typescript_event_unions(
        typescript_renderer, envelope, candidate_envelope, variants
    )
    return (
        black.format_str(
            python_base + "\n\n" + python_extra,
            mode=black.Mode(
                line_length=88,
                target_versions={black.TargetVersion.PY312},
            ),
        ),
        typescript_base + "\n\n" + typescript_extra,
    )



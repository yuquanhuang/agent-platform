def expected_generated_files(outputs: Mapping[Path, str]) -> set[Path]:
    return {path.resolve() for path in outputs}


def actual_generated_files() -> set[Path]:
    files: set[Path] = set()
    for root, suffixes in (
        (BACKEND_GENERATED, (".py",)),
        (FRONTEND_GENERATED, (".ts", ".json")),
    ):
        if root.is_dir():
            for suffix in suffixes:
                files.update(path.resolve() for path in root.glob(f"*{suffix}"))
    return files


def write_outputs(outputs: Mapping[Path, str]) -> None:
    expected = expected_generated_files(outputs)
    for stale in sorted(actual_generated_files() - expected):
        stale.unlink()
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"Generated {len(outputs)} contract files.")


def check_outputs(outputs: Mapping[Path, str]) -> int:
    failures: list[str] = []
    expected = expected_generated_files(outputs)
    for path, content in outputs.items():
        if not path.is_file():
            failures.append(f"missing generated file: {path.relative_to(PROJECT_ROOT)}")
        elif path.read_text(encoding="utf-8") != content:
            failures.append(
                f"outdated generated file: {path.relative_to(PROJECT_ROOT)}"
            )
    for stale in sorted(actual_generated_files() - expected):
        failures.append(f"stale generated file: {stale.relative_to(PROJECT_ROOT)}")
    if failures:
        print("Generated contract diff check FAILED:", file=sys.stderr)
        for failure in failures:
            print(f"- {failure}", file=sys.stderr)
        print("Run `make generate-contracts` and commit the result.", file=sys.stderr)
        return 1
    print(f"Generated contract diff check PASSED: {len(outputs)} files are current.")
    return 0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Compare committed generated files without modifying them.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        outputs = render_outputs()
    except (GenerationError, OSError, ValueError, yaml.YAMLError) as exc:
        print(f"Contract generation failed: {exc}", file=sys.stderr)
        return 2
    if args.check:
        return check_outputs(outputs)
    write_outputs(outputs)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
